"""Generate the committed relation-membership artifact the frontend derives ``RELATION_KEYS`` from.

Feature 105 / ADR 014: the set of relationship fields the entity page treats as *linkable* must come
from a single authoritative source (``RELATIONS``), not a hand-maintained ``new Set([...])`` in the
frontend — the five-list drift that causes bug B. This script is the single-source bridge: it imports
``RELATIONS`` and writes ``frontend/src/generated/relation-fields.json``.

It is **server-free** (a pure import — no running backend, unlike ``make generate-api``/openapi). CI
freshness is enforced by ``tests/unit/architecture/test_relation_fields_parity.py`` (the committed
file must equal a fresh generation); run this script and commit the result whenever ``RELATIONS``
changes.

Usage:  poetry run python scripts/utilities/gen_relation_fields.py
"""

from __future__ import annotations

import json
from pathlib import Path

from chronovista.services.wikidata_properties import RELATIONS

_OUT = (
    Path(__file__).resolve().parents[2]
    / "frontend"
    / "src"
    / "generated"
    / "relation-fields.json"
)


def build() -> dict[str, object]:
    """The membership payload: the sorted, de-duplicated relation field names from ``RELATIONS``."""
    return {
        "_comment": (
            "GENERATED by scripts/utilities/gen_relation_fields.py from "
            "chronovista.services.wikidata_properties.RELATIONS — do not edit by hand."
        ),
        "relations": sorted(set(RELATIONS.values())),
    }


def main() -> None:
    _OUT.parent.mkdir(parents=True, exist_ok=True)
    _OUT.write_text(
        json.dumps(build(), indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print(f"wrote {len(build()['relations'])} relation fields → {_OUT}")


if __name__ == "__main__":
    main()
