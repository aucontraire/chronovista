"""Block commits that carry the local library's content into the repository.

Investigating this project means reading real data. The failure mode is not
reading it — it is carrying it across into something that gets committed: a
test fixture, a docstring, a commit message, an issue body. Once pushed to a
public remote a force-push does not undo it: the orphaned commit stays
retrievable by SHA and is listed in the repository's public events feed. Only
GitHub Support can purge it.

Two kinds of content are caught, both listed in ``.private-terms`` (gitignored),
generated by ``gen_private_terms.py``:

- **Names** from the library, matched as whole words. A short acronym written in
  capitals (two to six characters, digits allowed, as in ``ABC``) matches only in
  capitals, because its lower-case form is often an ordinary English word.
- **Identifiers**: the owner's account identifiers and every video, channel and
  playlist ID in the library, stored as salted hashes so the list itself does not
  leak them. Identifier-shaped tokens in the text are hashed and looked up, and
  findings name the class, never the value. The prefix the owner's playlists
  share is matched literally.

The staged-diff mode checks **only lines being added**, so that touching an old
file does not demand its backlog be cleaned first. ``--tree`` checks every
tracked file; ``make pre-push`` runs it, so anything that slipped past the hook is
caught before it reaches the remote.

Fails **open** when the term list is missing, with a loud warning. A fresh
clone has no list, and a check that blocks every commit until someone runs a
database script does not survive contact with a bad morning.

Known gaps, stated so they are not mistaken for coverage:

- an identifier split across lines, base64-encoded, or broken by an invisible
  character is not caught (one glued inside a longer token is: see
  ``candidate_identifiers``);
- anyone holding the list can test whether a guessed identifier is in the library,
  which is acceptable only because the list is never committed;
- channel handles (``@name``), and video, channel and playlist titles and tags, are
  not listed: names come from entities and their aliases only;
- Wikidata QIDs are not covered;
- an identifier in a shape this check does not know (an old 18-character playlist ID,
  an uploads list starting ``UU``) is not covered; the generator counts these.

Usage
-----
    python scripts/utilities/check_private_terms.py             # staged diff
    python scripts/utilities/check_private_terms.py --msg FILE  # commit message
    python scripts/utilities/check_private_terms.py --text FILE # any text (- = stdin)
    python scripts/utilities/check_private_terms.py --tree      # every tracked file
"""

from __future__ import annotations

import hashlib
import pathlib
import re
import subprocess
import sys
import time
import unicodedata
from collections.abc import Iterable

try:
    from pydantic import BaseModel, Field
except ImportError:  # pragma: no cover — a Python without the project's dependencies
    print(
        "WARNING: pydantic is not installed for this Python — the private-content "
        "check did NOT run.\n"
        "         Run it inside the project environment (poetry run).",
        file=sys.stderr,
    )
    sys.exit(0)

ROOT = pathlib.Path(__file__).resolve().parents[2]
TERMS_FILE = ROOT / ".private-terms"

ACRONYM = re.compile(r"^(?=.*[A-Z])[A-Z0-9]{2,6}$")
"""A name matched only in capitals: 2-6 characters, every letter a capital."""

IDENTIFIER_TOKEN = re.compile(r"(?<![A-Za-z0-9_-])[A-Za-z0-9_-]+(?![A-Za-z0-9_-])")

ID_CLASS_LABELS = {
    "owner": "owner account identifier",
    "video": "library video identifier",
    "channel": "library channel identifier",
    "playlist": "library playlist identifier",
}
PREFIX_LABEL = "owner playlist prefix"


def fold(text: str) -> str:
    """Strip diacritics so accent variants match a single term.

    The match is already case-insensitive, but it was accent-sensitive: a term
    stored with a diacritic (``café``) did not catch the same name written
    without it (``cafe``), and that exact gap once let a real name reach the
    public docs and CLI help. Folding both the term list and the scanned text
    through NFKD and dropping combining marks closes it. Folding only ever
    *adds* matches (the accented form still folds to the same key), so it cannot
    cause a miss the old behaviour would have caught.
    """
    return "".join(
        c for c in unicodedata.normalize("NFKD", text) if not unicodedata.combining(c)
    )


def is_acronym(term: str) -> bool:
    return bool(ACRONYM.match(term))


def identifier_shape(token: str) -> str | None:
    """The canonical form to hash if ``token`` has an identifier's shape, else None.

    Shapes follow ``chronovista.models.youtube_types``: an 11-character video ID,
    ``UC`` + 22 for a channel (the owner's ID has the same shape), ``PL`` with 30-50
    characters for a playlist, and ``int_`` + 32 hex for an internal playlist ID.
    """
    if len(token) == 11:
        return token
    if token.startswith("UC") and len(token) == 24:
        return token
    if token.startswith("PL") and 30 <= len(token) <= 50:
        return token
    lowered = token.lower()
    if re.fullmatch(r"int_[0-9a-f]{32}", lowered):
        return lowered
    return None


def hash_identifier(salt: str, identifier: str) -> str:
    return hashlib.sha256(f"{salt}:{identifier}".encode()).hexdigest()[:32]


def candidate_identifiers(token: str) -> set[str]:
    """Every identifier-shaped value ``token`` holds, whole or inside it.

    A token is a maximal run of ``[A-Za-z0-9_-]``, so an ID glued to a filename
    (``<id>_en.vtt``), a percent-encoded link (``%3D<id>``) or a JSON escape
    (``\\n<id>``) is part of a longer token. Windows of each shape are tried too.
    Only a hash match is ever a finding, so the extra candidates add no false
    positives.
    """
    found = set()
    whole = identifier_shape(token)
    if whole is not None:
        found.add(whole)
    if len(token) > 11:
        found.update(token[i : i + 11] for i in range(len(token) - 10))
        for i in range(len(token) - 23):
            if token.startswith("UC", i):
                found.add(token[i : i + 24])
        for i in range(len(token) - 29):
            if token.startswith("PL", i):
                found.update(
                    token[i : i + n] for n in range(30, 51) if i + n <= len(token)
                )
        lowered = token.lower()
        for i in range(len(lowered) - 35):
            if lowered.startswith("int_", i) and re.fullmatch(
                r"int_[0-9a-f]{32}", lowered[i : i + 36]
            ):
                found.add(lowered[i : i + 36])
    return found


class Terms(BaseModel):
    """What ``.private-terms`` holds."""

    names: list[str] = Field(default_factory=list)
    salt: str | None = None
    id_hashes: dict[str, str] = Field(default_factory=dict)
    """Hash -> class (``owner``, ``video``, ``channel``, ``playlist``)."""
    prefixes: list[str] = Field(default_factory=list)
    problems: list[str] = Field(default_factory=list)
    """What could not be read; each is reported, because a quiet loss of coverage
    is how a leak passes."""


def parse_terms(lines: Iterable[str]) -> Terms:
    """Parse the term file. A line not starting with ``@`` is a name, as before
    records existed, so a names-only file reads exactly as it always did.
    """
    terms = Terms()
    salts: list[str] = []
    malformed = unknown_class = 0
    for raw in lines:
        line = raw.strip().lstrip("\ufeff")
        if not line:
            continue
        if not line.startswith("@"):
            terms.names.append(line)
            continue
        parts = line.split()
        if parts[0] == "@salt" and len(parts) == 2:
            salts.append(parts[1])
        elif parts[0] == "@id" and len(parts) == 3:
            id_class, digest = parts[1], parts[2].lower()
            if id_class not in ID_CLASS_LABELS:
                unknown_class += 1
            # Owner wins over channel: the same value is in both sets.
            elif terms.id_hashes.get(digest) != "owner":
                terms.id_hashes[digest] = id_class
        elif parts[0] == "@prefix" and len(parts) == 3:
            terms.prefixes.append(parts[2])
        else:
            malformed += 1
    if len(salts) == 1:
        terms.salt = salts[0]
    elif terms.id_hashes:
        terms.problems.append(
            f"{len(salts)} @salt lines (exactly one is needed): the identifier check "
            "did NOT run"
        )
        terms.id_hashes = {}
    if unknown_class:
        terms.problems.append(
            f"{unknown_class} @id lines with an unknown class ignored"
        )
    if malformed:
        terms.problems.append(f"{malformed} malformed @ lines ignored")
    return terms


class Matcher:
    """Every rule the check applies, built once and used by every mode."""

    def __init__(self, terms: Terms) -> None:
        acronyms = [t for t in terms.names if is_acronym(t)]
        others = [t for t in terms.names if not is_acronym(t)]
        self._acronyms = self._pattern(acronyms, flags=0)
        # Names are grouped by their first word: a line can only contain a name if
        # it contains that word, so each line runs only the small patterns for the
        # first words it has. One alternation over every name took ~25 s on --tree.
        by_first_word: dict[str, list[str]] = {}
        no_word: list[str] = []
        for term in others:
            words = re.findall(r"\w+", fold(term).casefold())
            if words:
                by_first_word.setdefault(words[0], []).append(term)
            else:
                no_word.append(term)
        self._names_by_first_word = {
            word: pattern
            for word, group in by_first_word.items()
            if (pattern := self._pattern(group, flags=re.IGNORECASE)) is not None
        }
        self._names_without_word = self._pattern(no_word, flags=re.IGNORECASE)
        self._salt = terms.salt
        self._id_hashes = terms.id_hashes
        self._prefix = (
            re.compile(
                "|".join(
                    # Anywhere, not only at a token start: a prefix glued to other
                    # characters still identifies the owner.
                    re.escape(p)
                    for p in sorted(terms.prefixes)
                )
            )
            if terms.prefixes
            else None
        )

    @staticmethod
    def _pattern(terms: list[str], *, flags: int) -> re.Pattern[str] | None:
        if not terms:
            return None
        ordered = sorted((fold(t) for t in terms), key=len, reverse=True)
        return re.compile(
            r"\b(" + "|".join(re.escape(t) for t in ordered) + r")\b", flags
        )

    def findings(self, line: str) -> list[str]:
        """What ``line`` would leak: matched names as written, identifiers by class."""
        folded = fold(line)
        found: list[str] = []
        if self._acronyms is not None:
            found.extend(set(self._acronyms.findall(folded)))
        for word in set(re.findall(r"\w+", folded.casefold())):
            pattern = self._names_by_first_word.get(word)
            if pattern is not None:
                found.extend(set(pattern.findall(folded)))
        if self._names_without_word is not None:
            found.extend(set(self._names_without_word.findall(folded)))
        if self._salt is not None and self._id_hashes:
            for token in IDENTIFIER_TOKEN.findall(line):
                if len(token) < 11:
                    continue
                for candidate in candidate_identifiers(token):
                    id_class = self._id_hashes.get(
                        hash_identifier(self._salt, candidate)
                    )
                    if id_class is not None:
                        found.append(ID_CLASS_LABELS[id_class])
        if self._prefix is not None and self._prefix.search(line):
            found.append(PREFIX_LABEL)
        return found


# A term list older than this no longer covers recently added entities. It is a
# warning rather than a block: coverage decays silently otherwise, but a hard
# stop on a stale file would fire on any machine without database access.
STALE_AFTER_DAYS = 14

# Image formats. The text check cannot read these, and a screenshot of the
# application shows real names visually — the one leak class this tool is blind
# to. Staging one earns a prompt to look at it.
IMAGE_SUFFIXES = {".png", ".jpg", ".jpeg", ".gif", ".webp", ".bmp", ".svg"}

# Tracked files --tree does not read, each with its reason. Verbatim third-party
# text that cannot be edited, where a word collides with a library name in
# capitals (so the acronym rule cannot help). Do not extend this to silence a
# finding in a file this project writes.
TREE_EXEMPT_PATHS = {
    "LICENSE": "the verbatim GPL text",
}


def load_terms() -> Terms | None:
    if not TERMS_FILE.exists():
        print(
            f"WARNING: {TERMS_FILE.name} not found — the private-content check did "
            "NOT run.\n"
            "         Generate it with: python scripts/utilities/gen_private_terms.py",
            file=sys.stderr,
        )
        return None
    age_days = (time.time() - TERMS_FILE.stat().st_mtime) / 86400
    if age_days > STALE_AFTER_DAYS:
        print(
            f"WARNING: {TERMS_FILE.name} is {int(age_days)} days old. Entities "
            "added since then are NOT covered.\n"
            "         Refresh: python scripts/utilities/gen_private_terms.py",
            file=sys.stderr,
        )
    terms = parse_terms(
        TERMS_FILE.read_text(encoding="utf-8", errors="replace").splitlines()
    )
    for problem in terms.problems:
        print(f"WARNING: {TERMS_FILE.name}: {problem}.", file=sys.stderr)
    if not (terms.names or terms.id_hashes or terms.prefixes):
        print(
            f"WARNING: {TERMS_FILE.name} is empty — the private-content check did "
            "NOT run.",
            file=sys.stderr,
        )
        return None
    return terms


def warn_about_staged_images() -> None:
    """Flag staged images, which no text check can inspect."""
    proc = subprocess.run(
        ["git", "diff", "--cached", "--name-only", "--diff-filter=ACM"],
        capture_output=True,
        text=True,
        check=False,
    )
    images = [
        f
        for f in proc.stdout.split()
        if pathlib.Path(f).suffix.lower() in IMAGE_SUFFIXES
    ]
    if images:
        print(
            "\nNOTE: this commit adds image(s) that no text check can read:\n"
            + "".join(f"  {f}\n" for f in images)
            + "A screenshot of the app shows real names on screen. Open each one\n"
            "and look before pushing.\n",
            file=sys.stderr,
        )


_HEADER_LEADS = (
    "index ",
    "diff --git",
    "new file mode",
    "deleted file mode",
    "old mode",
    "new mode",
    "similarity index",
    "rename to",
    "copy to",
)


def added_lines() -> list[tuple[str, str]]:
    """Return (path, line) for every line the staged diff adds."""
    proc = subprocess.run(
        ["git", "diff", "--cached", "--no-color", "-U0"],
        capture_output=True,
        check=False,
    )
    results: list[tuple[str, str]] = []
    current = "?"
    previous = before_previous = ""
    for line in proc.stdout.decode("utf-8", errors="replace").splitlines():
        # A file header is "+++ b/path" right after "--- ..." which itself follows the
        # file's "index"/"mode" line. An added line that starts with "++" looks the
        # same after a removed "--" line, and must be scanned.
        if (
            line.startswith("+++ ")
            and previous.startswith("--- ")
            and before_previous.startswith(_HEADER_LEADS)
        ):
            current = line[6:] if line.startswith("+++ b/") else line[4:]
        elif line.startswith("+"):
            results.append((current, line[1:]))
        before_previous, previous = previous, line
    return results


def tracked_lines() -> tuple[list[tuple[str, str]], int, int]:
    """(location, line) for every tracked text file, plus files scanned and skipped.

    Paths come from the repository root, wherever this runs from. A file with a NUL
    byte is binary: skipped and counted. Text that is not UTF-8 is scanned, with any
    undecodable byte replaced.
    """
    top = subprocess.run(
        ["git", "rev-parse", "--show-toplevel"],
        capture_output=True,
        text=True,
        check=False,
    ).stdout.strip()
    root = pathlib.Path(top) if top else pathlib.Path.cwd()
    proc = subprocess.run(
        ["git", "-C", str(root), "ls-files", "-z"], capture_output=True, check=False
    )
    results: list[tuple[str, str]] = []
    scanned = skipped = 0
    for name in proc.stdout.decode("utf-8", errors="replace").split("\0"):
        if not name or name in TREE_EXEMPT_PATHS:
            continue
        path = root / name
        if not path.is_file():
            continue
        data = path.read_bytes()
        if b"\0" in data:
            skipped += 1
            continue
        # Not UTF-8 is still text worth scanning; undecodable bytes are replaced.
        text = data.decode("utf-8", errors="replace")
        scanned += 1
        for number, line in enumerate(text.splitlines(), start=1):
            results.append((f"{name}:{number}", line))
    return results, scanned, skipped


def report(findings: list[tuple[str, str]]) -> int:
    if not findings:
        return 0
    print(
        "\nBlocked: content from the local library would enter the repository.\n",
        file=sys.stderr,
    )
    for where, what in findings:
        print(f"  {where}: {what!r}", file=sys.stderr)
    print(
        "\nUse neutral placeholder data in fixtures, docs, and commit messages.\n"
        "Real names and IDs belong in the database and your local notes, never in\n"
        "a commit — a public push cannot be fully undone.\n"
        "\nIf this is a false positive, reword it, or add the term to a documented\n"
        "exemption set in gen_private_terms.py — do not bypass the hook.\n",
        file=sys.stderr,
    )
    return 1


def main(argv: list[str]) -> int:
    terms = load_terms()
    if terms is None:
        return 0
    matcher = Matcher(terms)
    findings: list[tuple[str, str]] = []

    if len(argv) >= 2 and argv[0] == "--msg":
        message = pathlib.Path(argv[1]).read_text(encoding="utf-8", errors="replace")
        findings.extend(("commit message", m) for m in set(matcher.findings(message)))
    elif argv and argv[0] == "--text":
        # Arbitrary text that never passes through git: issue bodies, pull
        # request descriptions, release notes, a forum post. Nothing can hook
        # those, so they need a check that can be run by hand before posting.
        #   python scripts/utilities/check_private_terms.py --text body.md
        #   pbpaste | python scripts/utilities/check_private_terms.py --text -
        raw = (
            sys.stdin.read()
            if len(argv) < 2 or argv[1] == "-"
            else pathlib.Path(argv[1]).read_text(encoding="utf-8", errors="replace")
        )
        for line in raw.splitlines():
            findings.extend(("text", m) for m in matcher.findings(line))
        findings = sorted(set(findings))
        if not findings:
            print("Clean — no library content found.")
    elif argv and argv[0] == "--tree":
        lines, scanned, skipped = tracked_lines()
        for where, line in lines:
            findings.extend((where, m) for m in set(matcher.findings(line)))
        print(
            f"Scanned {scanned} tracked files ({skipped} binary skipped): "
            f"{len(findings)} findings.",
            file=sys.stderr,
        )
    else:
        for path, line in added_lines():
            findings.extend((path, m) for m in set(matcher.findings(line)))
        warn_about_staged_images()

    return report(findings)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
